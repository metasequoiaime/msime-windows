// theme.ts resolveTheme(): a surface set to dark / light wins, otherwise the global mode.
bool ResolveSurfaceLight(const SettingsModel &model, const char *surfacePath);
bool SystemPrefersLight();

// The built-in skins (CandidateSkinCatalog::BuiltInIds), in the skin page's order.
const std::vector<std::string> &BuiltinSkins();
bool IsBuiltinSkin(const std::string &id);

// External skin entry of appearance.external_candidate_skins, or null.
const Json *FindExternalSkin(const SettingsModel &model, const std::string &id);
// Base of a skin id: the id itself for a built-in skin, the manifest's base otherwise (a built-in
// skin or canvas; shared bases arrive already mapped to fluent).
std::string SkinBase(const SettingsModel &model, const std::string &id);
// skins/<id>/<relative> under appearance.candidate_skin_directory.
std::wstring SkinResourcePath(const SettingsModel &model, const std::string &id, const std::string &relative);

// Candidate font of the previews: appearance.english_font_css_family followed by the
// supplementary families, at the size the preview host inherits.
struct CandidateFont
{
    std::wstring primary = L"Segoe UI";
    std::vector<std::wstring> fallbacks;
    float size = 16.0f;
};
CandidateFont ReadCandidateFont(const SettingsModel &model);

// skins/ under appearance.candidate_skin_directory (the data directory's skins folder by default).
std::filesystem::path SkinsRoot(const SettingsModel &model);

// Surface, border and text color of a skin's candidate window, as the caret state indicator
// draws them: read from the same skin manifests as the candidate window (built-in look under
// skins/default, then the external skin's own colors), a translucent surface flattened onto
// the base's opaque one.
struct CandidateLook
{
    D2D1_COLOR_F bg = {}, border = {}, text = {};
};

CandidateLook ResolveCandidateLook(const SettingsModel &model, const std::string &skinId, bool light);

// Look of the floating toolbar preview.
struct ToolbarLook
{
    D2D1_COLOR_F bg = {}, border = {}, handle = {}, divider = {}, icon = {};
    float radius = 8.0f;     // multiplied by the scale
    float iconRadius = 6.0f; // multiplied by the scale
    // box-shadow passes in CSS terms: x, y, blur, alpha.
    struct Shadow
    {
        float x, y, blur, alpha;
    };
    std::vector<Shadow> shadows;

    // A skin's image mode ([toolbar] mode = "image"): one background image with the buttons
    // placed on it, as FloatingToolbarPresenter draws it. Sizes are in DIPs before scaling.
    bool imageMode = false;
    // Only schema_version 2 skins play their animated images.
    bool animated = false;
    std::wstring image;
    SizeF imageSize{};
    // The skin's manifest and folder: which buttons show, and so where they go, depends on the
    // preview's options (LayoutToolbarImageButtons).
    std::shared_ptr<const CandidateSkinCatalog::Package> package;
    std::filesystem::path directory;
};
ToolbarLook ResolveToolbarLook(const SettingsModel &model, const std::string &skinId, bool light);

// Window that repaints when an image decoded in the background is ready. Without one,
// images decode on the spot.
void SetImageLoadWindow(HWND hwnd);
// Starts decoding an image for CachedBitmap ahead of its first frame.
void PrefetchImage(const std::wstring &path);
// Bitmap of an image file, cached per render target (msimeui's cache holds only a
// few, and a page of skins shows many). Null until its pixels are decoded.
ID2D1Bitmap *CachedBitmap(msimeui::DeviceResources &dr, const std::wstring &path, D2D1_SIZE_F *size = nullptr);
// The current frame of an APNG / GIF when `animated` is set (msimeui's animation clock; the
// window repaints when the next one is due), otherwise CachedBitmap's still image.
ID2D1Bitmap *PreviewFrame(msimeui::DeviceResources &dr, const std::wstring &path, bool animated,
                          D2D1_SIZE_F *size = nullptr);
SizeF ImageFileSize(const std::wstring &path);

// A candidate window with sample candidates, drawn by the candidate window's own scene
// (CandidateSkinScene): same skin manifests, same controls, so it looks exactly like the real
// one. Page arrows and the scroll-expand button follow the skin's switches; the expand panel
// stays collapsed. Hovering highlights a candidate; clicks do nothing.
class CandidatePreview : public msimeui::Container
{
  public:
    struct Options
    {
        bool horizontal = false;
        size_t pageSize = 6;
        bool helpcode = true;
        bool preedit = true;
        // 0 takes the candidate font size.
        float preeditFontSize = 0.0f;
        // The candidate text color setting ("auto" keeps the skin's).
        std::string textColor = "auto";
        bool fitContent = false;
    };

    CandidatePreview();
    void Set(const SettingsModel &model, const std::string &skinId, bool light, const CandidateFont &font,
             const Options &options);

  private:
    std::unique_ptr<CandidateSkinScene> scene_;
    // Roots replaced by a rebuild. The window may still point at a visual in one of them as
    // the hovered or focused one, so they live on for a while instead of being freed at once.
    std::vector<std::shared_ptr<msimeui::Visual>> retired_;
};

// `.ftb-preview-host .status-bar` with the icons of ftb/default.html.
class ToolbarPreview : public msimeui::Visual
{
  public:
    struct Options
    {
        float scale = 1.0f;
        float iconSize = 24.0f;
        bool shadow = true;
        // fullwidth, punctuation, character_set, emoji, screen_keyboard, settings
        bool items[6] = {true, true, true, true, false, true};
        bool centered = false; // host justify-content: center
    };

    void Set(const ToolbarLook &look, const Options &options);

    SizeF Measure(const SizeF &availableSize) override;
    void Arrange(const RectF &finalRect) override;
    void Render(msimeui::DeviceResources &dr) override;

  private:
    float BarWidth() const;
    // The image mode's own scale: the toolbar multiplies the skin's DIPs by scale * iconSize / 24.
    float ImageScale() const;
    // The image mode's extent in DIPs before scaling: the background and every placed button.
    SizeF ImageExtent() const;
    void RenderImage(msimeui::DeviceResources &dr);

    ToolbarLook look_;
    // The image mode's buttons for the current options, from LayoutToolbarImageButtons.
    std::vector<ToolbarImageButtonSlot> slots_;
    Options options_;
    msimeui::ShadowCache shadows_[2];
};

